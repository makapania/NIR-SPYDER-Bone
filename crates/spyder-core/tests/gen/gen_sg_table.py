"""Generate crates/spyder-core/src/preprocess/sg_table.rs: Savitzky-Golay weights frozen from spyder_ref.

PLAN section 8 Phase 1 gate: SG weights must match spyder_ref BITWISE. spyder_ref computes them with numpy's
SVD pseudo-inverse (`_sg_matrix`), which no Rust code can reproduce bit for bit, so the weights of every
(window, polyorder, deriv) used by shipped or planned chains are frozen here as IEEE-754 bit patterns
(the "shipped table" route of PLAN v2 section 7). Other combinations fall back to a Householder-QR solve in
Rust, checked against spyder_ref to ~1e-16 relative (tests/operators.rs).

What is stored is M = D @ pinv(V), i.e. spyder_ref's `_sg_matrix` BEFORE its final division by
(h**deriv * delta**deriv). Rust performs that division exactly as numpy does, so the result is bitwise equal
for any delta. Rows: the centre weights (`sg_centre_weights`, positions [h]) and, for combinations whose
chains use mode "interp", the edge rows (positions 0..h-1 and W-h..W-1), each from the same call spyder_ref
makes (matmul results depend on the shape of the call).

Run:  <dasp venv>/python.exe crates/spyder-core/tests/gen/gen_sg_table.py
"""
import math
import sys
from pathlib import Path

import numpy as np

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).parent))
from refpath import import_spyder_ref, REPO  # noqa: E402

sr, where = import_spyder_ref()

# every (window, polyorder, deriv) in the planning model/transfer/engine files (tally of 2026-10-03)
COMBOS = [(31, 3, 2), (23, 3, 2), (23, 2, 1), (35, 2, 1), (41, 2, 1), (29, 2, 1), (27, 3, 2), (11, 2, 1),
          (13, 3, 2), (43, 3, 2), (33, 3, 2), (49, 3, 1), (23, 3, 1), (21, 3, 2), (37, 3, 2), (17, 3, 2),
          (25, 2, 1), (15, 3, 2), (29, 3, 2)]
# combinations with an "interp" chain somewhere (edge rows stored too); 31/3/2 because interp is scipy's default
WITH_EDGES = {(31, 3, 2), (35, 2, 1), (41, 2, 1), (29, 2, 1), (27, 3, 2), (11, 2, 1), (23, 3, 1)}


def sg_unscaled(window, polyorder, deriv, positions):
    """spyder_ref._sg_matrix line by line, without the final division."""
    h = window // 2
    t = np.arange(window, dtype=float)
    u = (t - h) / h
    m = np.arange(polyorder + 1)
    V = u[:, None] ** m[None, :]
    pinv = np.linalg.pinv(V)
    ue = (np.asarray(positions, float) - h) / h
    D = np.zeros((len(ue), polyorder + 1))
    for k in range(deriv, polyorder + 1):
        D[:, k] = math.factorial(k) / math.factorial(k - deriv) * ue ** (k - deriv)
    return D @ pinv


def bits(a):
    return [f"0x{v:016x}" for v in np.ascontiguousarray(a, dtype="<f8").ravel().view("<u8")]


def rust_array(name, a):
    b = bits(a)
    lines = [", ".join(b[i:i + 4]) for i in range(0, len(b), 4)]
    return f"const {name}: &[u64] = &[\n    " + ",\n    ".join(lines) + ",\n];\n" if b else f"const {name}: &[u64] = &[];\n"


out = ["// @generated by crates/spyder-core/tests/gen/gen_sg_table.py from spyder_ref. DO NOT EDIT.",
       "// Savitzky-Golay M = D @ pinv(V) (spyder_ref `_sg_matrix` before dividing by h^deriv * delta^deriv),",
       "// as IEEE-754 bit patterns. `left`/`right` are row-major (h rows x window), empty when not stored.",
       "",
       "pub(crate) struct SgEntry {",
       "    pub window: usize,",
       "    pub polyorder: usize,",
       "    pub deriv: usize,",
       "    pub centre: &'static [u64],",
       "    pub left: &'static [u64],",
       "    pub right: &'static [u64],",
       "}",
       ""]
entries = []
for (W, P, d) in COMBOS:
    h = W // 2
    tag = f"W{W}_P{P}_D{d}"
    c = sg_unscaled(W, P, d, [h])[0]
    for delta in (1.0, 2.0):
        assert np.array_equal(c / (h ** d * delta ** d), sr.sg_centre_weights(W, P, d, delta)), (W, P, d, delta)
    out.append(rust_array(f"C_{tag}", c))
    if (W, P, d) in WITH_EDGES:
        L = sg_unscaled(W, P, d, np.arange(h))
        R = sg_unscaled(W, P, d, np.arange(W - h, W))
        for delta in (1.0, 2.0):
            assert np.array_equal(L / (h ** d * delta ** d), sr._sg_matrix(W, P, d, delta, np.arange(h)))
            assert np.array_equal(R / (h ** d * delta ** d), sr._sg_matrix(W, P, d, delta, np.arange(W - h, W)))
        out.append(rust_array(f"L_{tag}", L))
        out.append(rust_array(f"R_{tag}", R))
        entries.append(f"    SgEntry {{ window: {W}, polyorder: {P}, deriv: {d}, centre: C_{tag}, left: L_{tag}, right: R_{tag} }},")
    else:
        entries.append(f"    SgEntry {{ window: {W}, polyorder: {P}, deriv: {d}, centre: C_{tag}, left: &[], right: &[] }},")
out.append("pub(crate) static SG_TABLE: &[SgEntry] = &[")
out += entries
out.append("];")
dest = REPO / "crates" / "spyder-core" / "src" / "preprocess" / "sg_table.rs"
dest.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(f"wrote {dest} ({len(COMBOS)} combinations, {len(WITH_EDGES)} with edge rows) from {where}; numpy {np.__version__}")
